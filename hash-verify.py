def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def manifest(root: Path) -> dict[str, str]:
    if not root.exists():
        raise FileNotFoundError(f"Dataset root does not exist: {root}")

    return {
        path.relative_to(root).as_posix(): sha256_file(path)
        for path in sorted(root.rglob("*"))
        if path.is_file() and path.suffix.lower() in DATA_SUFFIXES
    }


def main(args: argparse.Namespace) -> int:
    repo_manifest = manifest(args.repo_root)
    recovered_manifest = manifest(args.recovered_root)

    repo_files = set(repo_manifest)
    recovered_files = set(recovered_manifest)
    common_files = repo_files & recovered_files
    missing_in_repo = sorted(recovered_files - repo_files)
    extra_in_repo = sorted(repo_files - recovered_files)
    hash_mismatches = sorted(
        path for path in common_files if repo_manifest[path] != recovered_manifest[path]
    )

    print("repo_root", args.repo_root)
    print("recovered_root", args.recovered_root)
    print("repo_files", len(repo_manifest))
    print("recovered_files", len(recovered_manifest))
    print("common_files", len(common_files))
    print("missing_in_repo", len(missing_in_repo))
    print("extra_in_repo", len(extra_in_repo))
    print("hash_mismatches", len(hash_mismatches))
    print("repo_set_files", sum(path.endswith(".set") for path in repo_manifest))
    print("repo_fdt_files", sum(path.endswith(".fdt") for path in repo_manifest))
    print(
        "recovered_set_files",
        sum(path.endswith(".set") for path in recovered_manifest),
    )
    print(
        "recovered_fdt_files",
        sum(path.endswith(".fdt") for path in recovered_manifest),
    )

    for sample_file in SAMPLE_FILES:
        print(
            "sample",
            sample_file,
            repo_manifest.get(sample_file) == recovered_manifest.get(sample_file),
            repo_manifest.get(sample_file),
        )

    if missing_in_repo:
        print("missing_examples", missing_in_repo[: args.example_limit])
    if extra_in_repo:
        print("extra_examples", extra_in_repo[: args.example_limit])
    if hash_mismatches:
        print("mismatch_examples", hash_mismatches[: args.example_limit])

    if missing_in_repo or extra_in_repo or hash_mismatches:
        return 1
    return 0


